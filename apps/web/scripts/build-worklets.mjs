// Concatenates the worklet sources (ES modules, unit-tested in Node) into the
// plain scripts the browser loads with audioWorklet.addModule("/worklets/…").
// Worklet modules cannot import app code reliably, so each output inlines the
// shared resampler; `import` lines are dropped and `export` keywords removed.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const src = (name) =>
  readFileSync(join(root, "worklets", name), "utf8")
    .replace(/^\/\/ @ts-check\n/m, "")
    .replace(/^import .*\n/gm, "")
    .replace(/^export (class|const|function) /gm, "$1 ")

const outDir = join(root, "public", "worklets")
mkdirSync(outDir, { recursive: true })
const banner = "// Generated by scripts/build-worklets.mjs from apps/web/worklets/. Do not edit.\n"
for (const [out, files] of [["capture.js", ["resampler.js", "capture.js"]], ["player.js", ["resampler.js", "player.js"]]]) {
  writeFileSync(join(outDir, out), banner + "(() => {\n" + files.map(src).join("\n") + "\n})()\n")
}
