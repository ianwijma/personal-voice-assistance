// Lists the characters: every `src/characters/library/<id>.ts` except the baseline (which the host imports
// directly) becomes one line `"<id>": () => import("./library/<id>.ts")` in src/characters/library.generated.ts
// (git-ignored). Each `import()` is its own chunk, loaded only when a viewer picks that character; nobody edits a
// shared list (docs/CHARACTERS.md §7). Run before dev, build, check and test (package.json, vitest.config.ts).
//   node scripts/build-characters.mjs           write once (only when the list changed)
//   node scripts/build-characters.mjs --watch   rewrite whenever a file is added to or removed from library/
// Why not `import.meta.glob`: with Next 16.4's Turbopack its lazy entries end up inside the page's own chunk
// (checked with scripts/bundle-sizes.mjs), while a plain `import()` gets a chunk of its own.
import { existsSync, readdirSync, readFileSync, watch, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const library = join(root, "src", "characters", "library")
const out = join(root, "src", "characters", "library.generated.ts")
const BASELINE = "sine-lines"

export const characterIds = () =>
  readdirSync(library)
    .filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts") && !f.endsWith(".test.ts") && !f.startsWith("_") && !f.startsWith("."))
    .map((f) => f.slice(0, -3))
    .filter((id) => id !== BASELINE)
    .sort()

/** Write the list if it changed; returns the ids. */
export const generateCharacterRegistry = () => {
  const ids = characterIds()
  const text = [
    "// Generated by scripts/build-characters.mjs from src/characters/library/. Do not edit; it is not committed.",
    "// The baseline (sine-lines) is not here: the host imports it directly.",
    "export const loaders: { readonly [id: string]: () => Promise<{ readonly default?: unknown }> } = {",
    ...ids.map((id, i) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(`./library/${id}.ts`)})${i < ids.length - 1 ? "," : ""}`),
    "}",
    ""
  ].join("\n")
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text)
  return ids
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateCharacterRegistry()
  if (process.argv.includes("--watch")) {
    watch(library, () => generateCharacterRegistry())
    console.log("[characters] watching src/characters/library/")
  }
}
