import { expect, type Page } from "@playwright/test"
import { loginAdmin, MOCK, mock, test } from "./fixtures.ts"

// Admin › Assistants (docs/ASSISTANTS.md §7.1, mock-up docs/mockups/assistants/admin.html), against the mock's protocol 7
// handlers: the list, the seven tabs of an assistant (each saves through `assistant.save`, with dirty marks), a stale
// save, a field error from the server on its field, the delete dialog naming the devices, and the on/off switch.
// Mock data: Jeff (on the browser defaults, the kitchen iPad and the phone), T3 (defaults), Keuken (kitchen iPad).

const open = async (page: Page, baseURL: string | undefined, id: string, tab = "basics") => {
  await loginAdmin(page, baseURL, `#settings/assistants/${id}/${tab}`)
  await expect(page.getByTestId("assistant-page")).toHaveAttribute("data-assistant", id)
}
const tabButton = (page: Page, tab: string) => page.locator(`[role=tab][data-tab=${tab}]`)
const field = (page: Page, path: string) => page.locator(`[data-field="${path}"]`)
const saveButton = (page: Page) => page.getByTestId("page-footer").getByRole("button", { name: "Save", exact: true })
const saved = async () => (await mock.log()).messages.filter((m) => m.type === "assistant.save")
const lastSave = async () => (await saved()).at(-1) as unknown as { assistant: Record<string, any> } | undefined
const touch = (id: string, patch: Record<string, unknown>) => fetch(`${MOCK}/mock/assistant`, { method: "POST", body: JSON.stringify({ id, patch }) })

test.beforeEach(async () => {
  await mock.scenario("devices")
})

