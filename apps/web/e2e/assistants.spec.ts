test("Basics: edit, dirty marks (field, tab, navigation), Save, and the mark clears", async ({ page, baseURL }) => {
  await open(page, baseURL, "jeff")
  await expect(saveButton(page)).toBeDisabled()
  await expect(page.locator("[data-mark=dirty]")).toHaveCount(0)
  await page.getByLabel("Purpose").fill("Everyday questions, and the house.")
  await expect(field(page, "purpose").getByTestId("unsaved-marker")).toBeVisible()
  await expect(tabButton(page, "basics").locator("[data-mark=dirty]")).toBeVisible()
  await expect(tabButton(page, "behaviour").locator("[data-mark=dirty]")).toHaveCount(0)
  await expect(page.getByTestId("nav-assistants-jeff").locator("[data-mark=dirty]")).toBeVisible()
  await expect(page.getByTestId("footer-note")).toHaveText("Unsaved changes")
  await saveButton(page).click()
  await expect(page.getByTestId("footer-note")).toHaveText("Saved. Applies from the next turn.")
  await expect(page.locator("[data-mark=dirty]")).toHaveCount(0)
  await expect(field(page, "purpose").getByTestId("unsaved-marker")).toHaveCount(0)
  const sent = (await lastSave())!.assistant
  expect(sent).toMatchObject({ id: "jeff", rev: 0, purpose: "Everyday questions, and the house." })
  // The save came back as a push with the next rev: the header shows it, and a reload keeps it.
  await expect(page.getByText("Everyday questions, and the house.").first()).toBeVisible()
  await page.reload()
  await expect(page.getByLabel("Purpose")).toHaveValue("Everyday questions, and the house.")
  await page.getByLabel("Purpose").fill("Again.")
  await saveButton(page).click()
  await expect(page.getByTestId("footer-note")).toHaveText("Saved. Applies from the next turn.")
  expect((await lastSave())!.assistant.rev).toBe(1)
})

