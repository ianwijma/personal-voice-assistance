test("a stale save: the page is told, drops its edits and shows the newest version", async ({ page, baseURL }) => {
  await open(page, baseURL, "jeff")
  await page.getByLabel("Purpose").fill("My edit.")
  // Another admin changes the assistant: the page notices, the edit stays until the user decides.
  await touch("jeff", { purpose: "Changed elsewhere." })
  await expect(page.getByTestId("behind")).toContainText("Changed somewhere else")
  await expect(page.getByLabel("Purpose")).toHaveValue("My edit.")
  await saveButton(page).click()
  await expect(page.getByTestId("toasts")).toContainText("Jeff was changed somewhere else")
  await expect(page.getByLabel("Purpose")).toHaveValue("Changed elsewhere.")
  await expect(saveButton(page)).toBeDisabled()
  await expect(page.getByTestId("behind")).toHaveCount(0)
  expect((await saved()).at(-1)).toMatchObject({ assistant: { rev: 0 } })
  // Now it saves, from the new rev.
  await page.getByLabel("Purpose").fill("Third.")
  await saveButton(page).click()
  await expect(page.getByTestId("footer-note")).toContainText("Saved")
  expect((await lastSave())!.assistant.rev).toBe(1)
})

