test("unsaved edits stay across tabs, and leaving the assistant asks first", async ({ page, baseURL }) => {
  await open(page, baseURL, "jeff")
  await page.getByLabel("Purpose").fill("Edited.")
  await tabButton(page, "behaviour").click()
  await expect(page.getByTestId("leave-dialog")).toHaveCount(0)
  await tabButton(page, "basics").click()
  await expect(page.getByLabel("Purpose")).toHaveValue("Edited.")
  expect(new URL(page.url()).hash).toBe("#settings/assistants/jeff/basics")
  await page.getByTestId("nav-assistants-t3").click()
  await expect(page.getByTestId("leave-dialog")).toBeVisible()
  await page.getByRole("button", { name: "Stay" }).click()
  await expect(page.getByLabel("Purpose")).toHaveValue("Edited.")
  await page.getByTestId("nav-assistants-t3").click()
  await page.getByRole("button", { name: "Discard changes" }).click()
  await expect(page.getByTestId("assistant-page")).toHaveAttribute("data-assistant", "t3")
})

