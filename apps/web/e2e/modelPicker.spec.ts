  test("a model that is not downloaded downloads in its row, with progress and cancel; once installed it can be chosen", async ({ page, baseURL }) => {
    await page_(page, baseURL, "jeff/hearing")
    await open(page)
    await tab(page, "sherpa").click()
    const whisper = row(page, "sherpa:whisper-turbo")
    await expect(action(whisper, "download")).toHaveAccessibleName("Download Whisper turbo (565 MB)")
    // Pressing the row downloads it; it does not choose it.
    await action(whisper, "download").click()
    await expect(whisper).toHaveAttribute("data-local", "downloading")
    const progress = whisper.getByRole("progressbar", { name: "Downloading Whisper turbo" })
    await expect(progress).toBeVisible()
    await expect.poll(async () => Number(await progress.getAttribute("aria-valuenow") ?? 0)).toBeGreaterThan(0)
    await expect(whisper.getByTestId("model-download-progress")).toContainText(/\d+%/)
    await action(whisper, "cancel").click()
    await expect(whisper).toHaveAttribute("data-local", "not_installed")
    await main(page, "sherpa:whisper-turbo").click()
    await expect(whisper).toHaveAttribute("data-local", "downloading")
    await expect(picker(page)).toContainText("Parakeet v2")
    await expect(whisper).toHaveAttribute("data-local", "installed", { timeout: 20_000 })
    await expect(action(whisper, "download")).toHaveCount(0)
    await main(page, "sherpa:whisper-turbo").click()
    await expect(popup(page)).toBeHidden()
    await expect(picker(page)).toContainText("Whisper turbo")
    await expect(field(page, "hearing.model").getByTestId("unsaved-marker")).toBeVisible()
    // The model takes a language: the Language setting follows the chosen row.
    await expect(page.getByLabel("Language", { exact: true })).toBeEnabled()
    await saveButton(page).click()
    await expect(page.getByTestId("footer-note")).toContainText("Saved")
    expect((await saves()).at(-1)!.assistant.hearing).toMatchObject({ engine: "sherpa", model: "whisper-turbo" })
  })

