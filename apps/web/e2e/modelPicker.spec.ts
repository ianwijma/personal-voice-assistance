import type { Locator, Page } from "@playwright/test"
import { expect, gotoAdmin, loginAdmin, MOCK, mock, test } from "./fixtures.ts"

// The model pickers (docs/MODEL-PICKERS.md §6; the mock's /api/models/): Assistants › Jeff › Language model and Hearing
// show the language model and the recogniser as pickers built like the voice picker. Mock data (scenario "devices"):
// Anthropic API ready (haiku, sonnet, opus, an older haiku), Claude subscription not set up until its list is forced,
// OpenRouter without a key, the home model's list failed (the model Keuken uses is listed as "not in the list"),
// Offline stand-in. Recognisers: On this machine (Parakeet v2, Nemotron and Zipformer installed; Whisper turbo and
// Parakeet Ultra not), Deepgram without a key. Favourites: Claude Haiku 5.5 and gpt-oss-20b (llm), Parakeet v2 (stt).

const picker = (page: Page) => page.getByTestId("model-picker")
const popup = (page: Page) => page.getByTestId("model-popup")
const rows = (page: Page) => popup(page).getByTestId("model-row")
const row = (page: Page, key: string) => popup(page).locator(`[data-testid=model-row][data-model="${key}"]`)
const rowNames = (page: Page) => rows(page).locator("[data-row-main] > span:nth-of-type(2)").allInnerTexts()
const tab = (page: Page, id: string) => page.getByTestId("model-rail").locator(`[data-tab="${id}"]`)
const action = (r: Locator, name: string) => r.locator(`[data-action=${name}]`)
const main = (page: Page, key: string) => row(page, key).locator("[data-row-main]")
const field = (page: Page, path: string) => page.locator(`[data-field="${path}"]`)
const saveButton = (page: Page) => page.getByTestId("page-footer").getByRole("button", { name: "Save", exact: true })
const saves = async () => (await mock.log()).messages.filter((m) => m.type === "assistant.save") as unknown as Array<{ assistant: Record<string, any> }>
const force = async (provider: string, state: string) => {
  const r = await fetch(`${MOCK}/mock/models/state`, { method: "POST", body: JSON.stringify({ provider, state }) })
  expect(r.ok).toBe(true)
}
const open = async (page: Page) => {
  await picker(page).click()
  await expect(popup(page)).toBeVisible()
  await expect(popup(page).getByTestId("model-list")).not.toHaveAttribute("data-mode", /^$/)
  await expect(popup(page).getByTestId("model-list-empty")).toHaveCount(0) // not "Loading models…"
}
const page_ = async (page: Page, baseURL: string | undefined, hash: string) => {
  await loginAdmin(page, baseURL, `#settings/assistants/${hash}`)
  await expect(picker(page)).toBeVisible()
}

